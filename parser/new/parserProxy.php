function encrypt($data)
{
    $key = hex2bin(base64_decode('N2ZiMzE2OTk2MWVkZTJhYzU2MWUwMzNkZmNiNWYxZTBkMTgxMmI4ZTI5NGFlN2Q1NzEyMDg5ZWVjODM1YzlmZQ=='));
    $nonce = random_bytes(SODIUM_CRYPTO_SECRETBOX_NONCEBYTES);
    $encrypted = sodium_crypto_secretbox($data, $nonce, $key);
    return base64_encode(bin2hex($encrypted)) . base64_encode(bin2hex($nonce));
}

class Worker
{
    private $bookies = [];
    private $doNotEncrypt = [];
    private $origins = [];
    private $urls = [];
    private $differentUrl = '';
    private $specialJson = '';
    private $intervalBase = 0.5;
    // private $intervalBase = 5;
    private $checkInterval;
    private $usleep;
    private $debug = false;


    private $current = -1;
    private $previous = [];


    /**
     * Create new Worker class
     *
     * @param string[] $bookies Optional
     * @param string[] $origins Optional
     * @param string[] $urls Optional
     * @param string $differentUrl Optional
     * @param string[] $betexyBookies Optional
     * @param string[] $betexySources Optional
     * @param string[] $doNotEncrypt Optional
     *
     */
    public function __construct(
        $bookies,
        $origins = [],
        $urls = [],
        $differentUrl = '',
        $betexyBookies = [],
        $betexySources = [],
        $doNotEncrypt = []
    ) {
        $this->bookies = $bookies;
        $this->doNotEncrypt = $doNotEncrypt;
        $this->origins = $origins;
        $this->urls = $urls;
        $this->differentUrl = $differentUrl;
        if (!empty($betexyBookies)) {
            $this->specialJson = json_encode([
                "action" => "pool",
                "betexy_login" => "kboger@list.ru",
                "bookmakers" => $betexyBookies,
                "sources" => $betexySources,
            ]);
            $this->origins[] = 'betexy';
        }
        if (empty($this->origins)) {
            throw 'No origins!';
        }
        $this->checkInterval = $this->intervalBase / count($this->origins);
        $this->usleep = (int)(1000000 * $this->checkInterval);
        $this->debug = (bool)getenv('DEBUG_MODE', false);
        echo "Parsing started from: " . implode(', ', $this->origins) . PHP_EOL;
    }

    public function start(): void
    {
        $iteration = 0;
        while (true) {
            $startTime = microtime(true);
            $this->cycle();
            $finished = microtime(true) - $startTime;
            if ($finished < $this->checkInterval) {
                $this->echo("usleep ({$this->usleep})" . PHP_EOL);
                usleep($this->usleep);
            }
            if ($this->debug && $iteration > 14) {
                $this->echo("Breaking!");
                break;
            } elseif ($this->debug) {
                $iteration++;
            }
        }
    }

    private function cycle(): void
    {
        $startTime = microtime(true);
        $content = $this->getContent();
        $finished = microtime(true) - $startTime;
        $this->echo(date('Y-m-d H:i:s') . ' Got content ' . strlen($content) . ' in ' . number_format($finished, 3)
          . "s from {$this->origins[$this->current]}" . PHP_EOL);

        $parsed = json_decode($content, true);
        if (empty($parsed) || !is_array($parsed)) {
            $this->echo("Empty data - continue" . PHP_EOL);
            return;
        }

        $this->save($this->separate($parsed));
    }

    /**
     * @param array $parsed
     * @return array
     */
    private function separate($parsed): array
    {
        $result = [];
        foreach ($this->bookies as $bookie => $d) {
            $result[$bookie] = [];
        }
        foreach($parsed as $f) {
            foreach (['bookmaker', 'source', 'BK1_name', 'BK2_name',] as $key) {
                if (!empty($f[$key])) {
                    $f[$key] = mb_strtolower($f[$key]);
                }
            }
            foreach ($this->bookies as $bookie => $d) {
                if (count($d) === 1 && !empty($f['bookmaker']) && $f['bookmaker'] === mb_strtolower($d[0])) {
                    // By Bookie
                    $result[$bookie][] = $f;
                } elseif (count($d) === 1 && !empty($f['source']) && $f['source'] === mb_strtolower($d[0])) {
                    // By Source
                    $result[$bookie][] = $f;
                } elseif (count($d) === 3 && !empty($f['source']) && $f['source'] === mb_strtolower($d[1])
                  && !empty($f['bookmaker']) && $f['bookmaker'] === mb_strtolower($d[2])) {
                    // By Source and Bookie
                    $result[$bookie][] = $f;
                } elseif (count($d) === 2 &&
                    ((!empty($f['BK1_name']) && $f['BK1_name'] === mb_strtolower($d[0])
                            && !empty($f['BK2_name']) && $f['BK2_name'] === mb_strtolower($d[1]))
                      ||
                      (!empty($f['BK1_name']) && $f['BK1_name'] === mb_strtolower($d[1])
                            && (!empty($f['BK2_name']) && $f['BK2_name'] === mb_strtolower($d[0]))))
                ) {
                    // By Teams
                    $result[$bookie][] = $f;
                } else {
                    //$this->echo('Nothing in $f: ' . var_export($f, true) . PHP_EOL);
                }
            }
        }
        return $result;
    }

    /**
     * @param array $bets
     * @return void
     */
    private function save($bets): void
    {
        $readable = [];
        foreach	($bets as $bookie => $bets) {
            foreach ($bets as &$bet) {
                $bet['btsid'] = encrypt(time());
            }
            $toSave = empty($bets) ? '[]' : json_encode($bets);
            $readable[] = empty($bets) ? " {$bookie} => empty" : "{$bookie} => saved";

            file_put_contents(
                __DIR__."/current_{$bookie}.json",
                // do not encrypt some bookies
                in_array($bookie, $this->doNotEncrypt)
                    ? $toSave
                    : encrypt($toSave)
            );

            if (!empty($bets)) {
                $file_count = count(glob(__DIR__. "/history_{$bookie}_*.json"));
                if ($file_count < 20) {
                    file_put_contents(__DIR__."/history_{$bookie}_".time().".json", $toSave);
                }
            }
        }
        $this->echo(implode(', ', $readable) . PHP_EOL);
        //file_put_contents(__DIR__.'/current.json', $content);
    }

    private function getContent(): string
    {
        $content = '';
        $this->current++;
        if ($this->current >= count($this->origins)) {
            $this->current = 0;
        }
        if ($this->origins[$this->current] === 'betexy') {
            $content = getSpecials($this->specialJson);
        } elseif (substr($this->origins[$this->current], 0, 3) === 'url') {
            $content = getContentByUrl($this->urls[str_replace('url', '', $this->origins[$this->current])]);
        }
        if (!empty($content) &&
            (empty($this->previous[$this->current]) || $this->previous[$this->current] !== $content)) {
            $this->previous[$this->current] = $content;
        } elseif (!empty($this->previous[$this->current]) && $this->previous[$this->current] === $content) {
            $content = '';
        }
        $content_length = strlen($content);
        if ((int)$content_length === 265) {
            file_put_contents(__DIR__.'/last_265.json', $content);
        }
        if ($this->debug) {
            file_put_contents(__DIR__.'/'.$this->current.'-'.date('Y-m-d H:i:s').'.json', $content);
        }
        return $content;
    }

    /**
     * @param string $message
     * @return void
     */
    private function echo($message): void
    {
        if ($this->debug) {
            echo $message;
        }
    }

}

$worker = new Worker($bookies, $origins, $urls, $differentUrl, $betexyBookies, $betexySources, $doNotEncrypt);
